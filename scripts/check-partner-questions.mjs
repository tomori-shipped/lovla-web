import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const origin = new URL(process.argv[2] ?? 'http://127.0.0.1:3100');
assert(['127.0.0.1', 'localhost'].includes(origin.hostname));
const slug = '/blog/questions-to-ask-your-partner';
const canonical = `https://www.lovla.app${slug}`;
const image = '/blog/questions-to-ask-your-partner.png';
const pages = new Map(await Promise.all([slug, '/blog', '/sitemap.xml', '/blog/long-distance-relationship-gifts', '/blog/long-distance-anniversary-ideas'].map(async path => {
  const response = await fetch(new URL(path, origin)); assert.equal(response.status, 200, path); return [path, await response.text()];
})));
const html = pages.get(slug);
const visible = html.replace(/<script\b[^>]*>[\s\S]*?<\/script>/g, '');
assert.equal((visible.match(/<h1\b/g) ?? []).length, 1);
assert.equal((visible.match(/data-partner-question="true"/g) ?? []).length, 150);
const source = readFileSync('constants/blog/questions-to-ask-your-partner.ts', 'utf8');
const groups = JSON.parse(source.split('export const partnerQuestionGroups = ')[1].replace(/ as const;\s*$/, ''));
assert.equal(groups.length, 10);
assert(groups.every((group, index) => group.questions.length === 15 && group.start === index * 15 + 1));
assert.equal(new Set(groups.flatMap(group => group.questions)).size, 150);
assert(html.includes(`rel="canonical" href="${canonical}"`));
assert(html.includes(`property="og:image" content="https://www.lovla.app${image}"`));
assert(html.includes('name="twitter:card" content="summary_large_image"'));
const schema = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)].flatMap(match => JSON.parse(match[1])['@graph'] ?? []);
const article = schema.find(item => item['@type'] === 'BlogPosting');
assert.equal(article.author.name, 'The Lovla Team');
assert.equal(article.mainEntityOfPage['@id'], canonical);
assert(schema.some(item => item['@type'] === 'BreadcrumbList'));
assert(pages.get('/blog').includes(`href="${slug}"`));
assert(pages.get('/sitemap.xml').includes(canonical));
for (const related of ['things-to-do-on-facetime-with-your-partner', 'who-knows-me-better-questions-for-couples', 'turn-photo-into-coloring-page']) assert(visible.includes(`href="/blog/${related}"`));
for (const related of ['long-distance-relationship-gifts', 'long-distance-anniversary-ideas']) assert(pages.get('/blog').includes(`href="/blog/${related}"`));
const response = await fetch(new URL(image, origin));
assert.equal(response.status, 200);
assert.deepEqual(Buffer.from(await response.arrayBuffer()), readFileSync(`public${image}`));
console.log('PASS: 150 unique questions, 10 numbered groups, approved image delivery, metadata, schema, related links, and newer posts preserved.');
